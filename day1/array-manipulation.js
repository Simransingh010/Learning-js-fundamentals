let num = [1, 2, 4, 5, 6];
let sum = 0;
let count = 0;

for (let i = 0; i < num[i]; i++) {
  console.log(num[i]);
}

for (let i = 0; i < num[i]; i++) {
  sum = sum + num[i];
}

for (let i = 0; i < num[i]; i++) {
  if (num[i] > 5) {
    count = count + 1;
  }
}

console.log("Sum is: " + sum);
console.log("Number greater than 5 are: " + count);
